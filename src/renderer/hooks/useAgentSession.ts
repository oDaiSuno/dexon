import { useRef } from "react";
import type { UseAgentSessionOptions } from "./agent-session/shared";
import { useSessionActions } from "./agent-session/use-session-actions";
import { useSessionCommands } from "./agent-session/use-session-commands";
import { useSessionConnection } from "./agent-session/use-session-connection";
import { useSessionEffects } from "./agent-session/use-session-effects";
import { useSessionEvents } from "./agent-session/use-session-events";
import { useSessionExtensions } from "./agent-session/use-session-extensions";
import { useSessionHistory } from "./agent-session/use-session-history";
import { useSessionLifecycle } from "./agent-session/use-session-lifecycle";
import { useSessionReading } from "./agent-session/use-session-reading";
import { useSessionModels } from "./agent-session/use-session-models";
import { useSessionQueue } from "./agent-session/use-session-queue";
import { useSessionScroll } from "./agent-session/use-session-scroll";
import { useSessionState } from "./agent-session/use-session-state";
export type {
  AgentPhase,
  BuiltinSlashCommandResult,
  ChatInputHandle,
  CompactResultInfo,
  NoticeItem,
  QueuedMessages,
  SessionData,
  SlashCommandInfo,
  ThinkingLevelOption,
  UseAgentSessionOptions,
} from "./agent-session/shared";
export function useAgentSession(opts: UseAgentSessionOptions) {
  const readingVisible = opts.readingVisible ?? true;
  const readingVisibleRef = useRef(readingVisible);
  readingVisibleRef.current = readingVisible;
  const visualFrameIdsRef = useRef<Set<number>>(new Set());
  const state = useSessionState(opts);
  const history = useSessionHistory({ ...state, messageRefs: opts.messageRefs }, readingVisible);
  const connection = useSessionConnection({ ...state, ...history });
  const extensions = useSessionExtensions({ ...state, ...history, ...connection }, opts);
  const events = useSessionEvents({ ...state, ...history, ...connection, ...extensions, readingVisibleRef });
  const actions = useSessionActions({ ...state, ...history, ...connection, ...extensions, ...events });
  const models = useSessionModels({ ...state, ...history, ...connection, ...extensions, ...events, ...actions });
  const commands = useSessionCommands({
    ...state,
    ...history,
    ...connection,
    ...extensions,
    ...events,
    ...actions,
    ...models,
  });
  const queue = useSessionQueue(
    { ...state, ...history, ...connection, ...extensions, ...events, ...actions, ...models, ...commands },
    opts,
  );
  const scroll = useSessionScroll({
    ...state,
    ...history,
    ...connection,
    ...extensions,
    ...events,
    ...actions,
    ...models,
    ...commands,
    ...queue,
  });
  const lifecycle = useSessionLifecycle({
    ...state,
    ...history,
    ...connection,
    ...extensions,
    ...events,
    ...actions,
    ...models,
    ...commands,
    ...queue,
    ...scroll,
    readingVisible,
    readingVisibleRef,
    visualFrameIdsRef,
  });
  const reading = useSessionReading({ ...state, ...scroll }, readingVisible);
  const effects = useSessionEffects({
    ...state,
    ...history,
    ...connection,
    ...extensions,
    ...events,
    ...actions,
    ...models,
    ...commands,
    ...queue,
    ...scroll,
    ...lifecycle,
  });
  const {
    data,
    loading,
    error,
    activeLeafId,
    messages,
    entryIds,
    streamState,
    agentRunning,
    modelNames,
    modelList,
    modelCatalog,
    modelRefreshing,
    modelThinkingLevels,
    modelThinkingLevelMaps,
    newSessionModel,
    thinkingLevel,
    retryInfo,
    contextUsage,
    systemPrompt,
    forkingEntryId,
    isCompacting,
    compactError,
    compactResult,
    currentModel,
    displayModel,
    sessionStats,
    slashCommands,
    slashCommandsLoading,
    queuedMessages,
    previousCursor,
    loadingOlder,
    historyRevision,
    noticeState,
    interactiveTools,
    extensionStatuses,
    extensionWidgets,
    isNew,
    agentPhase,
    isAwayFromBottom,
    reattachAutoFollow,
    sessionIdRef,
    eventUnsubRef,
    messagesEndRef,
    liveContentEndRef,
    scrollContainerRef,
    lastUserMsgRef,
    pendingScrollToUserRef,
    initialScrollDoneRef,
    handleSend,
    handleAbort,
    handleFork,
    handleNavigate,
    handleModelChange,
    refreshModels,
    cancelModelRefresh,
    handleCompact,
    handleSteer,
    handleFollowUp,
    handlePromptWithStreamingBehavior,
    handleAbortCompaction,
    handleRecallQueue,
    handleBuiltinSlashCommand,
    handleThinkingLevelChange,
    loadSlashCommands,
    loadOlder,
    loadDeferredContent,
    setActiveLeafId,
    setData,
    setMessages,
    dispatch,
    setAgentRunning,
    setForkingEntryId,
    handleAgentEventRef,
  } = {
    ...state,
    ...history,
    ...connection,
    ...extensions,
    ...events,
    ...actions,
    ...models,
    ...commands,
    ...queue,
    ...scroll,
    ...lifecycle,
    ...reading,
    ...effects,
  };
  return {
    // State
    data,
    loading,
    error,
    activeLeafId,
    messages,
    entryIds,
    streamState,
    agentRunning,
    modelNames,
    modelList,
    modelCatalog,
    modelRefreshing,
    modelThinkingLevels,
    modelThinkingLevelMaps,
    newSessionModel,
    thinkingLevel,
    retryInfo,
    contextUsage,
    systemPrompt,
    forkingEntryId,
    isCompacting,
    compactError,
    compactResult,
    currentModel,
    displayModel,
    sessionStats,
    slashCommands,
    slashCommandsLoading,
    queuedMessages,
    hasOlder: previousCursor !== null,
    loadingOlder,
    historyRevision,
    notices: noticeState.visible,
    interactiveTools,
    extensionStatuses,
    extensionWidgets,
    isAutoModelSelection: isNew && newSessionModel === null,
    agentPhase,
    isNew,
    // "Scroll to bottom" affordance state + action
    isAwayFromBottom,
    reattachAutoFollow,
    // Refs
    sessionIdRef,
    eventUnsubRef,
    messagesEndRef,
    liveContentEndRef,
    scrollContainerRef,
    lastUserMsgRef,
    pendingScrollToUserRef,
    initialScrollDoneRef,
    // Actions
    handleSend,
    handleAbort,
    handleFork,
    handleNavigate,
    handleModelChange,
    refreshModels,
    cancelModelRefresh,
    handleCompact,
    handleSteer,
    handleFollowUp,
    handlePromptWithStreamingBehavior,
    handleAbortCompaction,
    handleRecallQueue,
    handleBuiltinSlashCommand,
    handleThinkingLevelChange,
    loadSlashCommands,
    loadOlder,
    loadDeferredContent,
    setActiveLeafId,
    setData,
    setMessages,
    dispatch,
    setAgentRunning,
    setForkingEntryId,
    // Subscriptions
    handleAgentEventRef,
  };
}
