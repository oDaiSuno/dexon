#!/usr/bin/env node
/**
 * Regenerates everything the renderer derives from the Framer project export
 * (src/renderer/styles/framer-tokens.json):
 *   - the --fx-* color blocks between the FRAMER-MIRROR markers in tokens.css
 *   - styles/typography.css, one .type-* class per Framer text style
 *
 *   node scripts/sync-framer-tokens.mjs          # rewrite both
 *   node scripts/sync-framer-tokens.mjs --check  # exit 1 if either is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { framerColorVariable, framerCssColor, framerTypeRule, readFramerTokens } from "./framer-tokens.mjs";
import { APP_MONO_FONT_FAMILY, APP_SANS_FONT_FAMILY } from "../src/shared/font-stack.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokensPath = path.join(root, "src/renderer/styles/tokens.css");
const typographyPath = path.join(root, "src/renderer/styles/typography.css");

function mirror(theme) {
  const { colors } = readFramerTokens();
  return Object.entries(colors)
    .map(([framerPath, value]) => `  ${framerColorVariable(framerPath)}: ${framerCssColor(value[theme])};`)
    .join("\n");
}

export function renderTokens(css) {
  let next = css;
  for (const theme of ["light", "dark"]) {
    const start = `/* FRAMER-MIRROR:${theme}:start */`;
    const end = `/* FRAMER-MIRROR:${theme}:end */`;
    const from = next.indexOf(start);
    const to = next.indexOf(end);
    if (from < 0 || to < from) throw new Error(`tokens.css is missing the ${theme} FRAMER-MIRROR markers`);
    next = `${next.slice(0, from + start.length)}\n${mirror(theme)}\n  ${next.slice(to)}`;
  }
  return next;
}

function fontFamilyVariable(family) {
  if (APP_SANS_FONT_FAMILY.startsWith(`"${family}"`)) return "var(--font-sans)";
  if (APP_MONO_FONT_FAMILY.startsWith(`"${family}"`)) return "var(--font-mono)";
  throw new Error(`Framer text style family ${family} is not the head of a shared font stack`);
}

export function renderTypography() {
  const { textStyles } = readFramerTokens();
  const rules = Object.entries(textStyles).map(([framerPath, style]) =>
    framerTypeRule(framerPath, style, fontFamilyVariable(style.family)),
  );
  return `/* typography — generated by scripts/sync-framer-tokens.mjs from framer-tokens.json; do not edit. */\n\n${rules.join("\n\n")}\n`;
}

export function staleFramerOutputs() {
  const stale = [];
  const tokens = readFileSync(tokensPath, "utf8");
  if (renderTokens(tokens) !== tokens) stale.push("tokens.css");
  let typography;
  try {
    typography = readFileSync(typographyPath, "utf8");
  } catch {
    stale.push("typography.css");
    return stale;
  }
  if (renderTypography() !== typography) stale.push("typography.css");
  return stale;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = staleFramerOutputs();
    if (stale.length > 0) {
      console.error(
        `FAIL: ${stale.join("、")} 与 framer-tokens.json 不一致，运行 node --experimental-strip-types scripts/sync-framer-tokens.mjs`,
      );
      process.exitCode = 1;
    } else console.log("Framer mirror OK");
  } else {
    writeFileSync(tokensPath, renderTokens(readFileSync(tokensPath, "utf8")));
    writeFileSync(typographyPath, renderTypography());
    console.log("tokens.css Framer mirror and typography.css rewritten");
  }
}
